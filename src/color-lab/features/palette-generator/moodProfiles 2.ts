import { oklchToRgb, rgbToHex, type HexColor } from '@/shared/color'
import type { Harmony, Mood } from './types'

export type AnchorRole = 'main' | 'support' | 'accent' | 'neutral-light' | 'neutral-dark'

/** A curated OKLCH color the family is built from, with per-anchor jitter half-ranges. */
export interface MoodAnchor {
  h: number
  c: number
  l: number
  role: AnchorRole
  jitterH: number
  jitterC: number
  jitterL: number
}

/** Hue window in degrees; wraps when start > end (e.g. 340→160 crosses 0). */
export interface HueWindow {
  start: number
  end: number
}

/** Hues in [start, end] may not exceed minChroma — e.g. Cozy forbids vivid cyan-to-purple. */
export interface ForbiddenZone {
  start: number
  end: number
  minChroma: number
}

/**
 * A complete sub-personality of a mood — its own anchors, hue windows,
 * chroma/lightness bounds, forbidden zones, warmth, contrast, and default
 * harmony. Regenerate picks among a mood's families so repeated generation
 * produces genuinely different palettes, not just a reshuffle of the same
 * anchors — see docs/algorithms.md.
 */
export interface PaletteFamily {
  id: string
  /** User-facing, friendly — e.g. "Berry Dessert". Never shown as a technical id. */
  label: string
  anchors: MoodAnchor[]
  hueWindows: HueWindow[]
  chromaRange: [number, number]
  lightnessRange: [number, number]
  forbidden: ForbiddenZone[]
  defaultHarmony: Harmony
  warmth: 'warm' | 'cool' | 'mixed'
  contrast: 'low' | 'medium' | 'high'
}

export interface MoodProfile {
  label: string
  description: string
  families: PaletteFamily[]
}

function anchor(
  h: number,
  c: number,
  l: number,
  role: AnchorRole,
  jitterH = 8,
  jitterC = 0.015,
  jitterL = 0.04,
): MoodAnchor {
  return { h, c, l, role, jitterH, jitterC, jitterL }
}

