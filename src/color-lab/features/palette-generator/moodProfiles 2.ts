export function isHueInWindow(hue: number, window: HueWindow): boolean {
  const h = ((hue % 360) + 360) % 360
  if (window.start <= window.end) return h >= window.start && h <= window.end
  return h >= window.start || h <= window.end
}

export function isHueInAnyWindow(hue: number, windows: HueWindow[]): boolean {
  return windows.some((w) => isHueInWindow(hue, w))
}

/** Small palette preview (hexes) for a mood's vibe chip, derived from its first family's anchors. */
export function moodPreviewHexes(mood: Mood, count = 5): HexColor[] {
  const family = MOOD_PROFILES[mood].families[0]
  return family.anchors.slice(0, count).map((a) => rgbToHex(oklchToRgb({ l: a.l, c: a.c, h: a.h })))
}
